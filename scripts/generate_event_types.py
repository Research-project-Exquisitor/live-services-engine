#!/usr/bin/env python3
"""Generate the UI event contract from Pydantic's JSON schema.

Run from the engine: python scripts/generate_event_types.py --output PATH
Use --check to fail if the checked-in TypeScript has drifted.
"""
import argparse
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.schemas.logging import ClientLogEvent, LogEvent


def ts_type(schema):
    if '$ref' in schema:
        return schema['$ref'].rsplit('/', 1)[-1]
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(ts_type(value) for value in schema['anyOf'])
    kind = schema.get('type')
    if kind == 'array':
        return f"Array<{ts_type(schema['items'])}>"
    if kind == 'object':
        return 'Record<string, unknown>'
    return {'integer': 'number', 'number': 'number', 'string': 'string',
            'boolean': 'boolean', 'null': 'null'}.get(kind, 'unknown')


def interface(name, schema):
    required = schema.get('required', [])
    fields = [f"  {key}{'' if key in required else '?'}: {ts_type(value)}"
              for key, value in schema['properties'].items()]
    return f'export interface {name} {{\n' + '\n'.join(fields) + '\n}\n'


def generate():
    schema = LogEvent.model_json_schema()
    client = ClientLogEvent.model_json_schema()
    # The producer always assigns these defaults, although intake accepts omission.
    client['required'] = list(set(client.get('required', [])) | {'event_id', 'v', 'data'})
    client['properties']['time'] = {'$ref': '#/$defs/ClientEventTime'}
    return ('// SPDX-FileCopyrightText: 2026 Ujjwal Sharma and Omar Shahbaz Khan\n'
            '// SPDX-License-Identifier: AGPL-3.0-or-later\n'
            '// Generated by live-services-engine/scripts/generate_event_types.py. Do not edit.\n\n'
            + f"export type EventType = {ts_type(schema['properties']['type'])}\n"
            + f"export type EventTarget = {ts_type(schema['properties']['target'])}\n\n"
            + interface('EventTime', schema['$defs']['EventTime']) + '\n'
            + 'export interface ClientEventTime { client: number; server?: null }\n\n'
            + interface('LogEvent', schema) + '\n' + interface('ClientLogEvent', client))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not args.output.exists() or args.output.read_text() != content:
            parser.exit(1, f'Generated event types differ: {args.output}\n')
    else:
        args.output.write_text(content)


if __name__ == '__main__':
    main()
